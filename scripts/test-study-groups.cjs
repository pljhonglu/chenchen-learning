const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {Intl,Date};
vm.createContext(context);
vm.runInContext(fs.readFileSync('public/study-groups.js','utf8'),context);
const Model = context.ChenchenStudyGroups;
const today = '2026-10-03';
const catalog = Object.entries(Model.CONFIG).flatMap(([type,c])=>Array.from({length:['math','decomp'].includes(type) ? 1 : c.count+2},(_,i)=>({id:`${type}-${i}`,type,title:`${type} ${i}`,source:type==='english' ? 'classroom' : undefined})));
const empty = {items:{},garden:{groups:{}},hiddenCourses:{}};
for (const [type,config] of Object.entries(Model.CONFIG)) {
  const group = Model.select(catalog,empty,type,'learn',today);
  assert.equal(group.count,config.count);
  assert.equal(group.items.length,['math','decomp'].includes(type) ? 1 : config.count);
  assert.equal(new Set(group.items.map(i=>i.id)).size,group.items.length);
  assert.equal(Model.select(catalog,empty,type,'review',today),null,'Unlearned content cannot enter review');
}
const learned = {items:Object.fromEntries(catalog.map(item=>[item.id,{learned:true,nextReview:'2026-10-05'}])),garden:{groups:{}},hiddenCourses:{}};
assert.equal(Model.reviews(catalog,learned,today).length,0,'No due content means rest');
learned.items['poem-1'].nextReview='2026-10-01';
const review=Model.select(catalog,learned,'poem','review',today);
assert.equal(review.items[0].id,'poem-1');
assert.equal(review.dueCount,1);
assert.equal(review.items.filter(i=>i.afterPractice).length,4,'Future filler is explicitly marked');
assert.equal(learned.items['poem-0'].nextReview,'2026-10-05','Selection does not mutate dates');
const small={...empty,items:{'poem-1':{learned:true,nextReview:'2026-10-01'}}};
assert.equal(Model.select(catalog,small,'poem','review',today),null,'A partial set never makes a review group');
const recent={...empty,garden:{groups:{a:{day:today,contentIds:['poem-0','poem-1']}}}};
assert.equal(Model.select(catalog,recent,'poem','learn',today).items[0].id,'poem-2','Fresh items are preferred');
const hidden={...learned,hiddenCourses:{'poem-1':true}};
assert.equal(Model.select(catalog,hidden,'poem','review',today),null,'Removed due item cannot make a group');
const english=catalog.filter(i=>i.type==='english').map(i=>({...i,source:'extension'}));
assert.equal(Model.select(english,empty,'english','learn',today),null,'Extension library is opt-in');
assert.equal(Model.select(english,learned,'english','learn',today).items.length,5,'Enrolled extension vocabulary is allowed');
learned.items['math-0'].nextReview='2026-10-03';
assert.equal(Model.select(catalog,learned,'math','review',today).count,10,'One due math skill generates ten questions');
assert.equal(Model.day(new Date('2026-10-02T16:00:00Z')),today,'Day rolls over at midnight Beijing');
assert.equal(Model.day(new Date('2026-10-02T15:59:59Z')),'2026-10-02');
console.log('study group selection: all checks passed');
